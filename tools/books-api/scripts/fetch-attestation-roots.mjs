// Обновить список корней аттестации Google: node scripts/fetch-attestation-roots.mjs
// Скачивает https://android.googleapis.com/attestation/root (список PEM) и пишет src/attest-roots.js: открытые ключи корней (SPKI, base64).
// Google меняет корни (новый ECDSA P-384 рядом со старым RSA), поэтому запускать перед выкладкой Worker и после сообщений об их ротации.
import { X509Certificate } from "node:crypto";
import { writeFileSync } from "node:fs";

const res = await fetch("https://android.googleapis.com/attestation/root", { headers: { "user-agent": "vetro-books-api/1" } });
if (!res.ok) throw new Error("HTTP " + res.status);
const pems = await res.json();
const spki = pems.map((pem) => {
  const c = new X509Certificate(pem);
  return { subject: c.subject.replace(/\n/g, ", "), notAfter: c.validTo, spki: c.publicKey.export({ type: "spki", format: "der" }).toString("base64") };
});

const body =
  "// GENERATED by scripts/fetch-attestation-roots.mjs on " + new Date().toISOString().slice(0, 10) + ": do not edit by hand.\n" +
  "// Корни аттестации ключей Android (https://android.googleapis.com/attestation/root): открытые ключи в формате SPKI, base64.\n" +
  "export const GOOGLE_ATTESTATION_ROOTS = [\n" +
  spki.map((r) => `  // ${r.subject}; valid to ${r.notAfter}\n  "${r.spki}",`).join("\n") +
  "\n];\n";
writeFileSync(new URL("../src/attest-roots.js", import.meta.url), body);
console.log(`wrote src/attest-roots.js with ${spki.length} roots:`);
for (const r of spki) console.log(" -", r.subject, "(valid to " + r.notAfter + ")");
