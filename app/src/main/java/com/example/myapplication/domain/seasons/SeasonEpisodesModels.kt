package com.example.myapplication.domain.seasons

import kotlinx.serialization.Serializable

/**
 * Чем строка является в цепочке франшизы.
 *
 * Сезоны и спецвыпуски живут в одном списке, но нумеруются по-разному: у сезона номер — это его
 * место в цепочке, по нему источники просмотра ищут релиз («3 сезон»), и вставить между сезонами
 * OVA значит сдвинуть все последующие номера и сломать сопоставление. Поэтому спецвыпуски
 * нумеруются ПОСЛЕ обычных сезонов, а отличает их этот признак.
 */
@Serializable
enum class SeasonKind {
    /** Обычный сезон: TV / TV_SHORT / ONA. */
    Season,
    /** OVA, спецвыпуск, полнометражка франшизы — смотрибельно, но вне сезонной нумерации. */
    Special,
}

/**
 * Один сезон франшизы с числом серий.
 *
 * [episodes] — сколько серий ДОСТУПНО сейчас: у завершённого сезона это заявленное число,
 * у онгоинга — только вышедшие (4 из анонсированных 12 → 4). Именно по нему строятся списки
 * серий, скачивание и плеер, чтобы не показывать невышедшие. Анонсированный итог — [totalEpisodes].
 */
@Serializable
data class SeasonInfo(
    /** Порядковый номер сезона в цепочке (1 = первый). */
    val seasonNumber: Int,
    /** Доступные серии (см. kdoc класса). 0 не пишем — такой сезон считается неразрешённым. */
    val episodes: Int,
    /** Заявленное число серий сезона; null = не анонсировано. Для UI-подписи «4 / 12». */
    val totalEpisodes: Int? = null,
    /** Сезон ещё выходит: [episodes] будет расти (для UI-пометки и коротких TTL). */
    val ongoing: Boolean = false,
    val anilistId: Int? = null,
    val malId: Int? = null,
    /** Откуда взято число серий: "AniList" | "Shikimori" | "MAL". */
    val source: String,
    /** Название сезона (romaji/en) — подпись в UI, отладка сопоставления. */
    val title: String? = null,
    /** Сезон или спецвыпуск — см. [SeasonKind]. Старые записи кэша читаются как сезоны. */
    val kind: SeasonKind = SeasonKind.Season,
    /** Формат по версии каталога («OVA», «MOVIE», «SPECIAL») — подпись спецвыпуска в UI. */
    val format: String? = null,
) {
    /** Строка-спецвыпуск: у неё не сезонная нумерация и другой заголовок в UI. */
    val isSpecial: Boolean get() = kind == SeasonKind.Special
}

/**
 * С какого номера нумеруются спецвыпуски.
 *
 * Отдельное числовое пространство, а не «следующий за последним сезоном»: номер сезона приходит и
 * из каталога, и от источников просмотра со СВОЕЙ шкалой, в которой бывают дыры («Найти ещё»
 * добавляет пятый сезон к двум известным). Считая номер спецвыпуска от количества строк, мы бы
 * рано или поздно выдали ему номер существующего сезона — а номер здесь не подпись, а ключ строки:
 * по нему живут ключи серий, прогресс просмотра и ключи элементов LazyColumn, который на дубликате
 * просто падает.
 *
 * Франшиз с тысячей сезонов не бывает, поэтому пересечься эти диапазоны не могут.
 */
const val SPECIAL_SEASON_BASE = 1000

/**
 * Тот же сезон, но в шкале ИСТОЧНИКА ПРОСМОТРА.
 *
 * Спецвыпуск — самостоятельный релиз со своей страницей, а не N-й сезон: его номер существует
 * только ради уникальности ключа. Источник, получивший такой номер, в лучшем случае ничего не
 * найдёт, а в худшем — отдаст чужой сезон (AniLibria берёт релиз ИНДЕКСОМ по цепочке франшизы).
 * Нормализация делается один раз на входе в [com.example.myapplication.media.source.SourceEngine],
 * чтобы её не пришлось повторять в каждом источнике.
 */
fun SeasonInfo.forSourceLookup(): SeasonInfo =
    if (isSpecial) copy(seasonNumber = 1) else this

/**
 * Заголовок строки в списке: «Сезон 3» у сезона, формат — у спецвыпуска.
 *
 * Номер у спецвыпуска технический (он продолжает сезонный ряд, чтобы ключи строк не совпадали) и
 * показывать его нельзя: «Сезон 5» напротив OVA — прямая дезинформация. Различить два OVA одного
 * тайтла помогает [SeasonInfo.title], который UI и так печатает отдельной строкой.
 */
fun SeasonInfo.displayLabel(ru: Boolean): String = when {
    !isSpecial -> if (ru) "Сезон $seasonNumber" else "Season $seasonNumber"
    format == "MOVIE" -> if (ru) "Фильм" else "Movie"
    format == "SPECIAL" -> if (ru) "Спецвыпуск" else "Special"
    format != null -> format
    else -> if (ru) "Спецвыпуск" else "Special"
}

/** Компактная подпись для чипа: «S3» / «OVA». */
fun SeasonInfo.shortLabel(ru: Boolean): String =
    if (isSpecial) displayLabel(ru) else "S$seasonNumber"

/**
 * Разложение тайтла по сезонам. [complete] — у всех найденных сезонов есть счётчик серий и
 * ни один не онгоинг; неполные записи перепроверяются каждым фоновым проходом (короткий TTL),
 * полные — раз в месяц.
 */
@Serializable
data class SeasonEpisodesEntry(
    val animeId: String,
    val seasons: List<SeasonInfo> = emptyList(),
    val complete: Boolean = false,
    val resolvedAt: Long = 0L,
    /**
     * Версия семантики резолва. Записи со старой версией считаются протухшими независимо от TTL:
     * иначе «полный» расклад, собранный прежним алгоритмом, провисел бы в кэше до месяца.
     * Поднимать при каждом изменении того, ЧТО кладём в [seasons] (см. [CURRENT_SCHEMA]).
     */
    val schema: Int = 0,
    /**
     * Когда по этому тайтлу последний раз прогоняли догон расклада ([SeasonCatchUp]).
     *
     * Живёт на записи, а не в памяти: WorkManager регулярно поднимает воркер в свежем процессе, и
     * пауза, существующая только в оперативке, не пережила бы ни одного запуска. Отдельно от
     * [resolvedAt] потому, что расклад перерезолвивается и сам по себе (TTL, открытие Details), а
     * это не означает, что источники просмотра уже спрашивали.
     */
    val lastCatchUpAt: Long = 0L,
) {
    companion object {
        /**
         * 1 — обход франшизы идёт СКВОЗЬ фильмы/OVA (иначе цепочка рвалась и терялись сезоны),
         * а [SeasonInfo.episodes] у онгоинга = вышедшие серии, не анонсированные.
         * 2 — сорванный обход больше не выдаётся за полный результат; версия поднята, чтобы
         *     выбросить уже накопленные «complete» записи из одного сезона (они жили месяц).
         * 3 — в расклад попадают OVA/спецвыпуски/полнометражки франшизы ([SeasonKind.Special]);
         *     накопленные записи их не содержат и должны перерезолвиться.
         */
        const val CURRENT_SCHEMA = 3
    }
}
