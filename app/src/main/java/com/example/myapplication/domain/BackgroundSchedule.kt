package com.example.myapplication.domain

/**
 * Как часто приложение работает в фоне — в одном месте, а не по координаторам.
 *
 * Каждый пункт здесь стоит батареи и запросов к чужим API, поэтому менять их стоит, видя все
 * сразу. TTL кэшей (ссылки, сезоны, журнал пробелов) живут у своих хранилищ: они про свежесть
 * данных, а не про пробуждения.
 */
object BackgroundSchedule {
    /** Облачная синхронизация (только для вошедших, не для гостя). */
    const val CLOUD_SYNC_HOURS = 1L

    /** Проверка новых серий в фоне. */
    const val EPISODE_CHECK_HOURS = 6L

    /** Повторная проверка серий не раньше, чем через это время, если её не форсировали. */
    const val EPISODE_CHECK_MIN_INTERVAL_MS = 30 * 60 * 1000L

    /** Обслуживание коллекции: недостающие поля, названия, ссылки. */
    const val COLLECTION_MAINTENANCE_HOURS = 6L
}
